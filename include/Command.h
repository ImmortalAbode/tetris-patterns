#ifndef COMMAND_H
#define COMMAND_H

// =====================================================================
// ПАТТЕРН: COMMAND (Команда)
// =====================================================================
// Задание методички (лаба 7) - меню рисования фигур с отменой/повтором -
// неприменимо буквально (в проекте нет меню и рисуемых примитивов). Идея та
// же: игровое действие (сдвиг, поворот, падение) оформляется как отдельный
// объект, а не прямой вызов функции. Это дает то же самое: 
// историю команд и отмену последнего хода.
//
// Участники:
//   - Command (этот файл)                 - интерфейс Execute()/Undo()
//   - ConcreteCommand (Commands.h)         - MoveLeftCommand, MoveRightCommand,
//     RotateCommand, DropCommand, MacroCommand
//   - Receiver (Tetromino, GameBoard, ...) - GameActions.h делает реальную
//     работу, команды - тонкая обертка над ней
//   - Invoker (CommandHistory)             - вызывает Execute(), хранит
//     последнюю команду для UndoLast()
//   - Client (main)                        - создает конкретные команды
// =====================================================================
class Command
{
public:
    virtual ~Command() = default;

    virtual void Execute() = 0;
    virtual void Undo() = 0;

    // Можно ли безопасно отменить эту команду (и, в составе макроса, команды
    // перед ней)? false у DropCommand означает, что фигура зафиксировалась
    // и была заменена новой - откат более ранних шагов того же макроса стал
    // бы бессмысленным (они ссылаются на уже не существующую фигуру).
    virtual bool IsReversible() const 
    { 
        return true; 
    }
};

#endif // COMMAND_H